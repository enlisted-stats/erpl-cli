const LANG_CODE = (JSON.parse(document.getElementById('data').textContent).meta || {}).lang || 'en';
const LANG = STRINGS[LANG_CODE] || STRINGS.en;
const PLURALS = new Intl.PluralRules(LANG_CODE);

// pluralForm picks a form from a list of plural forms for the number n.
function pluralForm(forms, n) {
  const i = { one: 0, few: 1, many: 2 }[PLURALS.select(n)] ?? forms.length - 1;
  return forms[Math.min(i, forms.length - 1)];
}

function tr(key, ...args) {
  let s = LANG[key] ?? STRINGS.en[key] ?? key;
  if (Array.isArray(s)) s = pluralForm(s, args[0]);
  return s.replace(/\{(\d)\}/g, (_, i) => args[i]);
}
